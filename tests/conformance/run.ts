// The conformance run: every renderer against every case, graded by structure.
//
//   npm run conformance
//
// Writes tests/conformance/SCORECARD.md (summary, committed) and
// tests/conformance/report/<renderer>.md (every failing case with its input,
// expected and actual outline and a diff; not committed).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { fixtureCases, specExamples, OUT_OF_SCOPE } from './cases'
import { expectedOutline, referenceHtml } from './expected'
import { outline } from './outline'
import { lineDiff } from './diff'
import { RENDERERS } from './renderers'

const here = dirname(fileURLToPath(import.meta.url))
const fixture = fixtureCases(readFileSync(join(here, 'fixture.md'), 'utf8'))
const spec = specExamples(readFileSync(join(here, 'gfm-spec.txt'), 'utf8'))

interface Result {
  id: string
  group: string
  title: string
  input: string
  expected: string
  actual: string
  pass: boolean
}

function grade(render: (md: string) => string, id: string, group: string, title: string, input: string, expected: string): Result {
  let actual: string
  try {
    actual = outline(render(input))
  } catch (e) {
    actual = `CRASH: ${(e as Error).message}`
  }
  return { id, group, title, input, expected, actual, pass: actual === expected }
}

const scorecard: string[] = [
  '# Renderer conformance scorecard',
  '',
  'Generated by `npm run conformance`. Each case is graded by **structure**: the renderer\'s output is',
  'reduced to an outline (block kinds, nesting, list starts, tight/loose, code text, table cells,',
  'link targets) and compared with the expected outline. Expected = the GitHub-compatible reference',
  '(micromark + GFM + math) with our additions applied — see `expected.ts`. The GFM spec examples',
  'are graded the same way; the spec\'s own expected HTML is used to calibrate the reference.',
  '',
]

mkdirSync(join(here, 'report'), { recursive: true })
const inScope = spec.filter((e) => !OUT_OF_SCOPE.has(e.section))

// Calibration: the reference against the spec's own expected HTML. Core examples
// assume no extensions, so they are rendered with none; extension examples with all.
{
  const core = (md: string) => referenceHtml(md, false)
  const misses = inScope.filter((e) => {
    try {
      return outline((e.extension ? referenceHtml : core)(e.markdown)) !== outline(e.html)
    } catch {
      return true
    }
  })
  scorecard.push(
    '## Calibration: the reference against the GFM spec',
    '',
    `${inScope.length - misses.length} / ${inScope.length} spec examples match (raw-HTML sections excluded). The misses are where`,
    'the 2019 spec text predates current CommonMark (a few emphasis edge cases) or GitHub has since changed',
    `(no more \`ftp://\` autolinks) — they are not grader errors: ${misses.map((e) => e.number).join(', ') || 'none'}.`,
    '',
  )
  console.log(`calibration: ${inScope.length - misses.length} / ${inScope.length}`)
}

for (const [name, render] of Object.entries(RENDERERS)) {
  const specResults = inScope.map((e) =>
    grade(render, `spec-${e.number}`, e.section, e.extension || 'core', e.markdown, expectedOutline(e.markdown)),
  )
  const fixtureResults = fixture.map((c) => grade(render, c.id, c.section, c.title, c.input, expectedOutline(c.input)))

  const tally = (rs: Result[]) => `${rs.filter((r) => r.pass).length} / ${rs.length}`
  const byGroup = (rs: Result[]) => {
    const groups = new Map<string, Result[]>()
    for (const r of rs) groups.set(r.group, [...(groups.get(r.group) ?? []), r])
    return groups
  }

  scorecard.push(`## Renderer: \`${name}\``, '')
  scorecard.push(`- **GFM spec examples:** ${tally(specResults)} pass (raw-HTML sections excluded)`)
  scorecard.push(`- **Fixture cases:** ${tally(fixtureResults)} pass`, '')
  scorecard.push('| Fixture section | Pass | Failing cases |', '|---|---|---|')
  for (const [g, rs] of byGroup(fixtureResults)) {
    const fails = rs.filter((r) => !r.pass).map((r) => r.id)
    scorecard.push(`| ${g} | ${tally(rs)} | ${fails.join(', ') || '—'} |`)
  }
  scorecard.push('', '| Spec section | Pass |', '|---|---|')
  for (const [g, rs] of byGroup(specResults)) scorecard.push(`| ${g} | ${tally(rs)} |`)
  scorecard.push('')

  // The detailed report: every failure, with everything needed to judge it.
  const report: string[] = [`# Failures: \`${name}\``, '']
  for (const r of [...fixtureResults, ...specResults].filter((x) => !x.pass)) {
    report.push(
      `## ${r.id} — ${r.title}`,
      '',
      `Section: ${r.group}`,
      '',
      'Input:',
      '',
      '~~~~~~~~markdown',
      r.input.replace(/\n$/, ''),
      '~~~~~~~~',
      '',
      'Diff (`-` expected, `+` actual):',
      '',
      '~~~~~~~~diff',
      lineDiff(r.expected, r.actual),
      '~~~~~~~~',
      '',
    )
  }
  writeFileSync(join(here, 'report', `${name}.md`), report.join('\n'))
  console.log(`${name}: spec ${tally(specResults)}, fixture ${tally(fixtureResults)}`)
}

writeFileSync(join(here, 'SCORECARD.md'), scorecard.join('\n'))
